-- PostgreSQL equivalent of schema.sql; applied on every app start, so keep it idempotent.
create table if not exists tracks (
  id       integer generated by default as identity primary key,
  title    text not null,
  artist   text not null,
  album    text,
  duration double precision,       -- seconds
  filename text not null unique,   -- file inside public/media/
  added_at timestamptz not null default now()
);

-- One row per (song, listener); the primary key enforces one rating per listener per song.
create table if not exists ratings (
  song_key   text not null,
  voter      text not null,
  artist     text not null,
  title      text not null,
  value      integer not null check (value in (1, -1)),
  created_at timestamptz not null default now(),
  primary key (song_key, voter)
);

create table if not exists users (
  id            integer generated by default as identity primary key,
  username      text not null,
  password_hash text not null,
  created_at    timestamptz not null default now()
);
-- Usernames are case-insensitive (SQLite uses `collate nocase`).
create unique index if not exists users_username_lower on users (lower(username));
